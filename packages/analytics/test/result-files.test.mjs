import test from 'node:test';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {createResultRecorder} from '../../toolkit/web/result-recorder.js';
import {analyticsDatasetFromResultFiles,loadAnalyticsResultSource,verifyOfflineResultIntegrity} from '../src/model.js';

async function make({code='ALU-1',attemptId='attempt-1',mode='code',issuer='centro',subjectId='user-1'}={}){
  const player=new EventTarget();
  player.packageId='course-1';
  player.contentRoot='sha256:'+'b'.repeat(64);
  const identity=mode==='platform'?{mode,issuer,subjectId,label:'Ana autenticada'}:{mode,issuer,code,label:'Ana'};
  const recorder=createResultRecorder(player,{identity,attemptId});
  recorder.record({type:'p2lrn:score',detail:{score:8,maxScore:10}});
  return recorder.finish();
}
test('Result generated by Player matches Analytics SHA-256 verification',async()=>{
  const result=await make();
  const integrity=await verifyOfflineResultIntegrity(result);
  assert.equal(integrity.valid,true);
  const dataset=await analyticsDatasetFromResultFiles([result]);
  assert.equal(dataset.learners[0].id,'code:centro:ALU-1');
  assert.equal(dataset.attempts.length,1);
  assert.equal(dataset.grades[0].authoritative,false);
  assert.equal(dataset.grades[0].value,8);
});
test('Teacher codes keep different learners separate, attempts merge by learner',async()=>{
  const results=[
    await make({code:'ALU-1',attemptId:'a1'}),
    await make({code:'ALU-2',attemptId:'a2'}),
    await make({code:'ALU-1',attemptId:'a3'})
  ];
  const dataset=await analyticsDatasetFromResultFiles(results);
  assert.equal(dataset.learners.length,2);
  assert.equal(dataset.attempts.length,3);
});
test('Platform identities are namespaced and not falsely verified',async()=>{
  const result=await make({mode:'platform',issuer:'my-lms',subjectId:'u123'});
  const data=await analyticsDatasetFromResultFiles([result]);
  assert.equal(data.learners[0].id,'platform:my-lms:u123');
  assert.equal(data.learners[0].metadata.identityVerified,false);
});
test('Analytics src accepts direct result path and static multi-result index',async()=>{
  const a=await make({code:'A',attemptId:'a'}),b=await make({code:'B',attemptId:'b'});
  const entries={
    'https://school.example/data/a.p2lrn-result':a,
    'https://school.example/data/b.p2lrn-result':b,
    'https://school.example/data/index.p2lrn-results.json':{
      schema:'https://p2lrn.org/schema/analytics-results-index/1',
      results:['a.p2lrn-result','b.p2lrn-result'],
    },
  };
  const calls=[];
  const fetcher=async url=>{calls.push(url);return {ok:!!entries[url],status:entries[url]?200:404,json:async()=>entries[url]};};
  const one=await loadAnalyticsResultSource('/data/a.p2lrn-result',{baseURL:'https://school.example/page/',fetcher});
  const all=await loadAnalyticsResultSource('/data/index.p2lrn-results.json',{baseURL:'https://school.example/page/',fetcher});
  assert.equal(one.attempts.length,1);
  assert.equal(all.attempts.length,2);
  assert.equal(all.learners.length,2);
  assert.equal(calls.length,4);
});
test('Analytics rejects modified files and cross-origin result references',async()=>{
  const result=await make();
  const changed={...result,identity:{...result.identity,code:'ALTERED'}};
  await assert.rejects(()=>analyticsDatasetFromResultFiles([changed]),/SHA-256/);
  const fetcher=async()=>({ok:true,json:async()=>({schema:'https://p2lrn.org/schema/analytics-results-index/1',results:['https://outside.example/steal.p2lrn-result']})});
  await assert.rejects(()=>loadAnalyticsResultSource('https://school.example/data/index.p2lrn-results.json',{fetcher}),/otro origen/);
});

test('Portable progress checkpoints remain in_progress and do not become grades',async()=>{
  const finished=await make({code:'ALU-17',attemptId:'transfer-1'});
  const checkpoint=structuredClone(finished);
  checkpoint.attempt.status='in_progress';
  checkpoint.attempt.finishedAt=null;
  checkpoint.transfer={schema:'https://p2lrn.org/schema/offline-progress-transfer/1',completedAttempts:[]};
  const body={...checkpoint};
  delete body.integrity;
  const canonical=value=>value===null||typeof value!=='object'
    ?JSON.stringify(value)
    :Array.isArray(value)?'['+value.map(canonical).join(',')+']'
    :'{'+Object.keys(value).sort().map(key=>JSON.stringify(key)+':'+canonical(value[key])).join(',')+'}';
  checkpoint.integrity={algorithm:'sha256',
    payloadDigest:'sha256:'+createHash('sha256').update(canonical(body)).digest('hex')};
  const dataset=await analyticsDatasetFromResultFiles([checkpoint]);
  assert.equal(dataset.learners.length,1);
  assert.equal(dataset.attempts.length,1);
  assert.equal(dataset.attempts[0].status,'in_progress');
  assert.equal(dataset.attempts[0].submittedAt,null);
  assert.equal(dataset.attempts[0].metadata.portableCheckpoint,true);
  assert.equal(dataset.grades.length,0);
});
