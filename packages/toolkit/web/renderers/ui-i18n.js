export function playerUiText(value,doc=globalThis.document){
  const source=String(value??'');
  const language=String(doc?.documentElement?.lang??'es');
  if(!/^en(?:-|$)/i.test(language))return source;
  if(Object.hasOwn(EN,source))return EN[source];
  // Counted statuses use fixed machine-readable numbers, never learner prose.
  let match;
  if((match=/^Faltan (\d+) preguntas? obligatorias?\.$/.exec(source)))
    return match[1]==='1'?'1 required question is missing.':match[1]+' required questions are missing.';
  if((match=/^Pregunta (\d+) de (\d+)$/.exec(source)))return 'Question '+match[1]+' of '+match[2];
  if((match=/^Progreso: pregunta (\d+) de (\d+)$/.exec(source)))return 'Progress: question '+match[1]+' of '+match[2];
  if((match=/^Intentos agotados \((\d+)\/(\d+)\)\.$/.exec(source)))return 'Attempts exhausted ('+match[1]+'/'+match[2]+').';
  if((match=/^Hueco (\d+)$/.exec(source)))return 'Blank '+match[1];
  if((match=/^completar con al menos un (\d+)%$/.exec(source)))return 'complete with at least '+match[1]+'%';
  if((match=/^aprobar con al menos un (\d+)%$/.exec(source)))return 'pass with at least '+match[1]+'%';
  if((match=/^\d+ \/ \d+ puntos$/.exec(source)))return source.replace(' puntos',' points');
  if((match=/^Pareja correcta\. (\d+)\/(\d+) parejas\.$/.exec(source)))
    return 'Correct match. '+match[1]+'/'+match[2]+' pairs.';
  if((match=/^Descubre dos cartas y forma parejas\. (\d+)\/(\d+) parejas\.$/.exec(source)))
    return 'Turn over two cards and find matching pairs. '+match[1]+'/'+match[2]+' pairs.';
  if((match=/^Crucigrama entregado: ([\d.]+)\/([\d.]+) puntos\.$/.exec(source)))
    return 'Crossword submitted: '+match[1]+'/'+match[2]+' points.';
  if((match=/^(\d+) participantes? conectados?$/.exec(source)))
    return match[1]+' participant'+(match[1]==='1'?'':'s')+' connected';
  if((match=/^Aportación (\d+)$/.exec(source)))return 'Contribution '+match[1];
  if((match=/^Comentario para la aportación (\d+)$/.exec(source)))return 'Comment on contribution '+match[1];
  if((match=/^Reto (\d+)$/.exec(source)))return 'Challenge '+match[1];
  if((match=/^Prueba (\d+) de (\d+)$/.exec(source)))return 'Trial '+match[1]+' of '+match[2];
  if((match=/^Tiempo restante: (\d+)s$/.exec(source)))return 'Time remaining: '+match[1]+'s';
  if((match=/^Ronda completada: (\d+)\/(\d+) aciertos\.$/.exec(source)))return 'Round completed: '+match[1]+'/'+match[2]+' correct.';
  if((match=/^Memoria completada: (\d+)\/(\d+) puntos\.$/.exec(source)))return 'Memory completed: '+match[1]+'/'+match[2]+' points.';
  if((match=/^Resultado: ([\d.]+)\s*\/\s*([\d.]+) puntos(?: \((\d+)%\))?\.$/.exec(source)))
    return 'Result: '+match[1]+'/'+match[2]+' points'+(match[3]?' ('+match[3]+'%)':'')+'.';
  if((match=/^Relaciones establecidas: (\d+) de (\d+)\. Puedes modificarlas sin conocer la corrección\.$/.exec(source)))
    return 'Matches made: '+match[1]+' of '+match[2]+'. You can change them before seeing the answers.';
  if((match=/^Respuesta encontrada\. (\d+)\/(\d+)\.$/.exec(source)))return 'Answer found. '+match[1]+'/'+match[2]+'.';
  if((match=/^Posición (\d+)$/.exec(source)))return 'Position '+match[1];
  if((match=/^La posición (\d+) ya está ocupada\.$/.exec(source)))return 'Position '+match[1]+' is already occupied.';
  if((match=/^Objeto colocado en la posición (\d+)\.$/.exec(source)))return 'Object placed in position '+match[1]+'.';
  if((match=/^Conexión correcta · (\d+)\/(\d+)$/.exec(source)))return 'Correct connection · '+match[1]+'/'+match[2];
  if((match=/^Reto (\d+) de (\d+)$/.exec(source)))return 'Challenge '+match[1]+' of '+match[2];
  if((match=/^Sopa completada: ([\d.]+)\/([\d.]+) puntos\.$/.exec(source)))
    return 'Word search completed: '+match[1]+'/'+match[2]+' points.';
  if((match=/^Respuesta: (.*)$/.exec(source)))return 'Answer: '+match[1];
  if((match=/^Cambiar categoría de (.*)$/.exec(source)))return 'Change category of '+match[1];
  if((match=/^Categoría (.*)$/.exec(source)))return 'Category '+match[1];
  if((match=/^Three\.js · física: (.*)$/.exec(source)))
    return 'Three.js · physics: '+(match[1]==='fallback sin físicas'?'fallback without physics':match[1]);
  return source;
}
