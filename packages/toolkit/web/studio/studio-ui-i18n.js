export function studioLanguage(doc=globalThis.document){
  return /^en(?:-|$)/i.test(String(doc?.documentElement?.lang??'es'))?'en':'es';
}
export function studioUiText(value,doc=globalThis.document){
  const text=String(value??'');
  if(studioLanguage(doc)!=='en')return text;
  if(Object.hasOwn(EN,text))return EN[text];
  const blankStarter='Escribe aquí el texto y selecciona la palabra que quieras ocultar. {{';
  if(text.startsWith(blankStarter))return EN[blankStarter]+text.slice(blankStarter.length);
  const numberedOption=/^Opción (\d+)$/.exec(text);
  if(numberedOption)return 'Option '+numberedOption[1];
  const letteredPair=/^Pareja ([A-Z])$/.exec(text);
  if(letteredPair)return 'Pair '+letteredPair[1];
  const question=/^Pregunta (\d+)$/.exec(text);
  if(question)return 'Question '+question[1];
  const statement=/^Afirmación (\d+)$/.exec(text);
  if(statement)return 'Statement '+statement[1];
  const changes=/^(\d+) cambio(s?)$/.exec(text);
  if(changes)return changes[1]+' change'+(changes[1]==='1'?'':'s');
  for(const prefix of ['JSON avanzado no válido: ','Actividad añadida al grupo: ','No se pudo mover la actividad: '])
    if(text.startsWith(prefix))return EN[prefix]+text.slice(prefix.length);
  return text;
}
// Only call this when creating *new default* content. Existing course data,
// authored questions, imported packages and free-text input are never rewritten.
export function studioNewDefaults(value,doc=globalThis.document){
  if(studioLanguage(doc)!=='en')return value;
  if(typeof value==='string')return studioUiText(value,doc);
  if(Array.isArray(value))return value.map(item=>studioNewDefaults(item,doc));
  if(value&&typeof value==='object')return Object.fromEntries(
    Object.entries(value).map(([key,item])=>[key,studioNewDefaults(item,doc)])
  );
  return value;
}
